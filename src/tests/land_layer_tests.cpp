#include "world/land_layer.h"
#include <cassert>
#include <cstdint>
int main() {
  using namespace kami::sl;
  const uint8_t bytes[]={0x12,0x34,0x10,0x4C};
  LandBitReader reader(bytes,sizeof(bytes));
  uint32_t v=0;
  assert(reader.bits_remaining()==32);
  assert(reader.peek_bits(4,v) && v==1 && reader.bit_position()==0);
  assert(reader.read_bits(4,v)&&v==1);
  assert(reader.read_bits(12,v)&&v==0x234);
  assert(reader.read_bits(8,v)&&v==16);
  assert(reader.read_bits(8,v)&&v==0x4C);
  assert(reader.bits_remaining()==0 && reader.bit_position()==32);
  assert(!reader.read_bits(1,v));
  LandBitReader empty(nullptr,0);
  assert(empty.bits_remaining()==0 && !empty.read_bits(1,v));
  assert(empty.read_bits(0,v) && v==0);
  LandBitReader aligner(bytes,sizeof(bytes));
  assert(aligner.skip_bits(3) && aligner.align_to_byte());
  assert(aligner.bit_position()==8 && aligner.align_to_byte());
  LandBitReader dword_reader(bytes,sizeof(bytes));
  uint32_t dword=0;
  assert(dword_reader.read_u32(dword) && dword==0x1234104C);
  LandBitReader word_reader(bytes,sizeof(bytes));
  uint16_t word=0;
  assert(word_reader.read_u16(word) && word==0x1234);
  LandBitReader byte_reader(bytes,sizeof(bytes));
  uint8_t byte=0;
  assert(byte_reader.read_u8(byte) && byte==0x12);
  LandBitReader skipper(bytes,sizeof(bytes));
  assert(skipper.skip_bits(16) && skipper.bit_position()==16);
  assert(!skipper.skip_bits(17) && skipper.bit_position()==16);
  LandBitReader excessive(bytes,sizeof(bytes));
  assert(!excessive.read_bits(33,v));
  assert(excessive.bits_remaining()==32);
  const uint8_t signed_data[]={0xF1};
  LandBitReader signed_reader(signed_data,1);
  int32_t signed_value=0;
  assert(signed_reader.read_signed_bits(4,signed_value) && signed_value==-1);
  assert(signed_reader.read_signed_bits(4,signed_value) && signed_value==1);
  LandBitReader header_reader(bytes,sizeof(bytes));
  LandGroupHeader header;
  assert(read_land_group_header(header_reader,header));
  assert(header.stride==0x1234 && header.patch_size==16 && header.layer_type==0x4C);
  const uint8_t patch_bytes[]={0x28,0x3F,0x80,0,0,0,0x10,0,0};
  LandBitReader patch_reader(patch_bytes,sizeof(patch_bytes));
  LandPatchHeader patch;
  assert(read_land_patch_header(patch_reader,patch));
  assert(patch.quant_wbits==0x28 && patch.dc_offset==1.0f && patch.range==16);
  const uint8_t marker_bytes[]={97,0};
  LandBitReader marker_reader(marker_bytes,sizeof(marker_bytes));
  bool ended=false;
  assert(read_land_patch_end(marker_reader,ended) && ended);
  assert(read_land_patch_end(marker_reader,ended) && !ended);
  const uint8_t all_zero_coefficients[64]={};
  LandBitReader zeros(all_zero_coefficients,sizeof(all_zero_coefficients));
  std::vector<int32_t> coefficients;
  assert(decode_land_coefficients(zeros,16,4,coefficients));
  assert(coefficients.size()==256);
  for (auto c:coefficients) assert(c==0);
  const uint8_t malformed_run[]={0x40};
  LandBitReader malformed(malformed_run,sizeof(malformed_run));
  assert(!decode_land_coefficients(malformed,16,4,coefficients));
  const uint8_t invalid_header[]={0,1,8,0x4C};
  LandBitReader bad(invalid_header,sizeof(invalid_header));
  assert(!read_land_group_header(bad,header));
  LandBitReader truncated(patch_bytes,2);
  assert(!read_land_patch_header(truncated,patch));
}
